SELECT
	o.order_date,
	SUM(oi.unit_price * oi.quantity) AS total
FROM
	orders o,
	order_items oi
WHERE
	o.order_id = oi.order_id
GROUP BY
	o.order_date
ORDER BY
	o.order_date;


