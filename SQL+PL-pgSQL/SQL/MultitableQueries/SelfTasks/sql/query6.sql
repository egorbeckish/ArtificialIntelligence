SELECT
	o.order_date,
	SUM(oi.unit_price * oi.quantity) AS total
FROM
	orders o
JOIN order_items oi ON
	o.order_id = oi.order_id
GROUP BY
	o.order_date
ORDER BY
	o.order_date;


SELECT
	o.order_date,
	SUM(oi.unit_price * oi.quantity) AS total
FROM
	orders o
NATURAL JOIN order_items oi
GROUP BY
	o.order_date
ORDER BY
	o.order_date;


SELECT
	o.order_date,
	SUM(oi.unit_price * oi.quantity) AS total
FROM
	orders o
JOIN order_items oi
		USING (order_id)
GROUP BY
	o.order_date
ORDER BY
	o.order_date;
